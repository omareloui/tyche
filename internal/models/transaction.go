package models

import (
	"time"

	"github.com/omareloui/tyche/internal/errs"
	"github.com/omareloui/tyche/internal/sanitizer"
	"github.com/omareloui/tyche/internal/valid"
)

type Transaction struct {
	ID           string
	Account      Account
	Amount       float64
	Kind         TxKind
	Category     *Category
	ToAccount    *Account
	Counterparty *Counterparty
	ToAmount     float64
	Description  string
	// Note is Markdown, stored as typed (see internal/markdown).
	Note string
	// Goal is set on its goal's transactions (in or out of its account).
	Goal        *Goal
	RecurrentTx *RecurrentTx
	// RecurrentTxID is the recurrent transaction it was generated by, as read
	// from the DB (RecurrentTx is only set when creating one).
	RecurrentTxID string
	// RecurrentAuto tells its recurrent transaction fulfills it by itself.
	RecurrentAuto bool
	// LoanGoalID is the goal whose loan it pays (one of the payments
	// scheduled on buying it), its Goal then.
	LoanGoalID  string
	ScheduledTo time.Time
	FulfilledAt time.Time
	NeedsReview bool
	FromSMS     bool
	SMSBody     string
	// FromImport tells it came from a CSV import.
	FromImport bool
	CreatedAt  time.Time
	// ReimbursesID is the expense this income pays back (part of).
	ReimbursesID string
	// Reimbursed is the total of the incomes reimbursing this expense.
	Reimbursed     float64
	Reimbursements []Transaction
	// TransferPairID is the other leg of the transfer between own accounts
	// this expense or income is half of (see transfer_pairs.go).
	TransferPairID string
	// TransferPair is the incoming leg, nested under the outgoing one.
	TransferPair *Transaction
	// Items are its lines (items bought, then charges), in order.
	Items []TxItem
	// ItemsCount is how many lines it has, set in lists where the lines
	// themselves aren't loaded.
	ItemsCount int
	// Receipt is its receipt's image, nil when none.
	Receipt *Receipt
	// Wishes are the wishlist items bought in it.
	Wishes []WishlistItem
	// ReceiptID is a scanned receipt to link on saving it.
	ReceiptID string
	// SplitPeople is how many people its bill is split with (see TxSplit),
	// only set on a transaction fetched alone.
	SplitPeople int
}

type commonFieldsForTxAndRtx struct {
	ID             string   `validate:"required,ulid"`
	AccountID      string   `validate:"required,ulid"`
	Amount         float64  `validate:"required"`
	Kind           uint8    `validate:"required"`
	CategoryID     string   `validate:"excluded_if=Kind 3,excluded_if=Kind 4,excluded_if=Kind 6,omitempty,ulid"`
	CounterpartyID string   `validate:"excluded_if=Kind 3,excluded_if=Kind 4,excluded_if=Kind 6,omitempty,ulid"`
	ToAccountID    string   `validate:"required_if=Kind 3,required_if=Kind 4,omitempty,ulid"`
	ToAmount       float64  `validate:"required_if=Kind 3,required_if=Kind 4"`
	Description    string   `conform:"trim"`
	Note           string   `conform:"trim" validate:"max=10000"`
	Items          []TxItem `validate:"max=200,dive"`
}

type createTransaction struct {
	commonFieldsForTxAndRtx
	ScheduledTo time.Time `validate:"required"`
}

func (t *Transaction) ViewAmount() string {
	return t.Account.Currency.Format(t.Amount)
}

func (t *Transaction) ViewNetAmount() string {
	return t.Account.Currency.Format(t.NetAmount())
}

// IsReimbursement reports whether the transaction pays back (part of) an
// expense.
func (t *Transaction) IsReimbursement() bool {
	return t.ReimbursesID != ""
}

// NetAmount is the amount minus what got reimbursed of it.
func (t *Transaction) NetAmount() float64 {
	return t.Amount - t.Reimbursed
}

// AnalysisAmount is the amount every analysis (spending, income, charts) must
// use: expenses count net of their reimbursements and the reimbursements
// themselves count as 0, as they're already netted from their expense. Both
// legs of a transfer pair count as 0, the money stays the user's.
func (t *Transaction) AnalysisAmount() float64 {
	if t.IsReimbursement() || t.IsTransferLeg() {
		return 0
	}
	return t.NetAmount()
}

func (t *Transaction) ViewToAmount() string {
	if t.ToAccount == nil {
		return ""
	}
	return t.ToAccount.Currency.Format(t.ToAmount)
}

func (t *Transaction) toValidate() *createTransaction {
	var catID, toAccID, cpID string

	if cat := t.Category; cat != nil {
		catID = cat.ID
	}
	if cp := t.Counterparty; cp != nil {
		cpID = cp.ID
	}
	if toAcc := t.ToAccount; toAcc != nil {
		toAccID = toAcc.ID
	}
	return &createTransaction{
		commonFieldsForTxAndRtx: commonFieldsForTxAndRtx{
			ID:             t.ID,
			AccountID:      t.Account.ID,
			Amount:         t.Amount,
			Kind:           uint8(t.Kind),
			CategoryID:     catID,
			CounterpartyID: cpID,
			ToAccountID:    toAccID,
			ToAmount:       t.ToAmount,
			Description:    t.Description,
			Note:           t.Note,
			Items:          t.Items,
		},
		ScheduledTo: t.ScheduledTo,
	}
}

func (t *Transaction) SanitizeAndValidate(sani *sanitizer.Sanitizer, valid *valid.Validator) error {
	tc := t.toValidate()
	if err := sani.SanitizeStruct(tc); err != nil {
		return errs.ErrSanitizer
	}
	if valerr := valid.Validate(tc); valerr != nil {
		return *valerr
	}
	return nil
}

// IsGoalTx reports whether it's in or out of a goal's account: a deposit, a
// withdrawal or the goal's purchase. Only the goal's actions make them.
func (t *Transaction) IsGoalTx() bool {
	return t.Account.IsGoal() || (t.ToAccount != nil && t.ToAccount.IsGoal())
}

// IsGoalPurchase reports whether it's the expense buying a goal.
// IsLoanPayment reports whether it pays the loan a goal was bought with.
func (t *Transaction) IsLoanPayment() bool {
	return t.LoanGoalID != ""
}

func (t *Transaction) IsGoalPurchase() bool {
	return t.Kind == ExpenseTxKind && t.Account.IsGoal()
}

// IsLocked reports whether it can't be edited nor duplicated: a goal's or a
// deleted account's.
// CanHoldWishes tells wishlist items can be marked bought in it: an expense
// of the user's (not locked, a reimbursement or a transfer's leg).
func (t *Transaction) CanHoldWishes() bool {
	return t.Kind == ExpenseTxKind && !t.IsLocked() && !t.IsTransferLeg() && !t.IsReimbursement() && !t.IsLoanPayment()
}

func (t *Transaction) IsLocked() bool {
	return t.IsGoalTx() || t.Account.IsDeleted() || (t.ToAccount != nil && t.ToAccount.IsDeleted())
}

// GoalAmount is what it put towards its goal (negative when taken out), in
// the goal's currency (at today's rate, from a holding in another one; see
// Goal.TxAmount), else in its goal account's.
func (t *Transaction) GoalAmount() float64 {
	if t.Goal != nil && t.Goal.Account != nil {
		return t.Goal.TxAmount(t)
	}
	switch {
	case t.ToAccount != nil && t.ToAccount.IsGoal():
		return t.ToAmount
	case t.Account.IsGoal():
		return -t.Amount
	}
	return 0
}

// GoalPercentage is GoalAmount as a percentage of its goal's price.
func (t *Transaction) GoalPercentage() float64 {
	if t.Goal == nil || t.Goal.Price == 0 {
		return 0
	}
	return t.GoalAmount() / t.Goal.Price * 100
}
